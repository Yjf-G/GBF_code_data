# Targeted re-run: SI B.1.4 Algorithm 4 (three-phase country coverage: sigma_i(n) / stability / net-change bootstrap)
#           + SI B.2.2 weight sensitivity (keep_index countries + target/goal two-level)
#           + SI B.2.3 endpoint robustness (including the per-series extrapolation export)
#   Computes a4/c3/c5 only, without re-running the whole pipeline (the long-running modules a1-a3/a5 are unaffected)
# Usage: Rscript scripts/run_c3c5_refresh.R   (a4 about 2-5 minutes, the rest takes seconds)
GBF_NO_AUTORUN <- TRUE
source("gbf_compute_pipeline.R")
source("gbf_compute_remaining.R")
res <- load_res_from_checkpoints()
i2t <- load_i2t()
t0 <- Sys.time()

a4 <- algo4_country_coverage(res$norm_indicator, i2t, res$coverage, res$norm_layer)
write_csv(a4$sigma_by_n, "data/output/uncertainty__a4_country_coverage__sigma_by_n.csv")
write_csv(a4$sigma_fits, "data/output/uncertainty__a4_country_coverage__sigma_fits.csv")
write_csv(a4$prop_stable, "data/output/uncertainty__a4_country_coverage__prop_stable.csv")
write_csv(a4$headline_boot, "data/output/uncertainty__a4_country_coverage__headline_boot.csv")
write_csv(a4$headline_summary, "data/output/uncertainty__a4_country_coverage__headline_summary.csv")
if (!dir.exists("data/fig_data/sup_fig8")) dir.create("data/fig_data/sup_fig8", recursive = TRUE)
write_csv(a4$sigma_by_n, "data/fig_data/sup_fig8/supfig8_sigma_curves.csv")
write_csv(a4$prop_stable, "data/fig_data/sup_fig8/supfig8_prop_stable.csv")
write_csv(a4$headline_boot, "data/fig_data/sup_fig8/supfig8_net_change_bootstrap.csv")
write_csv(a4$headline_summary, "data/fig_data/sup_fig8/supfig8_net_change_summary.csv")
cat(sprintf("[a4] %.1f s\n", as.numeric(difftime(Sys.time(), t0, units = "secs"))))

c3 <- weight_sensitivity(res$norm_indicator, i2t, res$coverage)
write_csv(c3, "data/output/uncertainty__c3_weight_sensitivity.csv")
if (!dir.exists("data/fig_data/sup_fig10")) dir.create("data/fig_data/sup_fig10", recursive = TRUE)
write_csv(c3, "data/fig_data/sup_fig10/supfig10_weight_sensitivity.csv")

c5 <- endpoint_robustness(res$norm_layer, res$coverage)
write_csv(c5$extrapolation_test, "data/output/c5_extrapolation_test.csv")
write_csv(c5$extrapolation_series, "data/output/c5_extrapolation_series.csv")
write_csv(c5$leave_one_year_out, "data/output/c5_leave_one_year_out.csv")
write_csv(c5$loo_max, "data/output/c5_loo_max.csv")
if (!dir.exists("data/fig_data/sup_fig11")) dir.create("data/fig_data/sup_fig11", recursive = TRUE)
write_csv(c5$leave_one_year_out, "data/fig_data/sup_fig11/supfig11_leave_one_year_out.csv")
write_csv(c5$extrapolation_test, "data/fig_data/sup_fig11/supfig11_extrapolation_test.csv")
write_csv(c5$extrapolation_series, "data/fig_data/sup_fig11/supfig11_extrapolation_series.csv")

cat(sprintf("[c3+c5] %.1f s\n", as.numeric(difftime(Sys.time(), t0, units = "secs"))))
cat("=== c3 (scheme × level) ===\n"); print(as.data.frame(c3), digits = 4)
cat("=== c5 extrapolation ===\n"); print(as.data.frame(c5$extrapolation_test), digits = 4)
cat("=== c5 loo_max ===\n"); print(as.data.frame(c5$loo_max), digits = 4)
cat("saved 7 CSVs; extrap series rows:", nrow(c5$extrapolation_series), "\n")
cat("C3C5_DONE\n")
